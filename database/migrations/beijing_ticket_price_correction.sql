matched AS (
    SELECT DISTINCT ON (s.id)
        s.id,
        r.price,
        r.note
    FROM scenic_spots s
    JOIN ticket_rules r
      ON (
          (position('%' in r.pattern) > 0 AND s.name ILIKE r.pattern)
          OR (position('%' in r.pattern) = 0 AND trim(s.name) = r.pattern)
      )
    WHERE COALESCE(s.city, '') IN ('北京', '北京市')
    ORDER BY s.id, r.priority
)
